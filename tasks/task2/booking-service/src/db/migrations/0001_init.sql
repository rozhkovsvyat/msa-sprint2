create table booking (
    id                   bigint generated by default as identity primary key,
    user_id              text           not null,
    hotel_id             text           not null,
    promo_code           text,
    discount_amount      numeric(10, 2) not null default 0,
    price                numeric(10, 2) not null,
    created_at           timestamptz    not null,
    -- true: исходная дата неизвестна (в монолите NULL), при переносе подставлено время миграции
    created_at_estimated boolean        not null default false,
    source               text           not null default 'booking-service'  -- booking-service | migration
);
create index booking_user_id_idx on booking (user_id);

-- Transactional outbox: событие пишется в одной транзакции с бронированием, публикует его OutboxPublisher.
create table outbox (
    id               bigint generated always as identity primary key,
    event_id         uuid        not null unique,
    aggregate_id     bigint      not null,
    event_type       text        not null,
    correlation_id   text        not null,
    payload          jsonb       not null,
    created_at       timestamptz not null default now(),
    published_at     timestamptz,
    failure_count    integer     not null default 0,
    last_error       text,
    next_attempt_at  timestamptz not null default now(),
    dead_lettered_at timestamptz  -- карантин: ошибку повтором не исправить, нужен разбор
);
create index outbox_pending_idx on outbox (next_attempt_at, id) where published_at is null and dead_lettered_at is null;
